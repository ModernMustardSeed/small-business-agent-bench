// Seeded randomness. The only randomness in the bench is task order and sample
// selection; both come from here, so a seed reproduces them exactly.

import { createHash } from 'node:crypto';

/** First four bytes of SHA-256 of the string, as an unsigned 32-bit integer. */
export function seedFromString(s: string): number {
  return createHash('sha256').update(s).digest().readUInt32BE(0);
}

export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function seededShuffle<T>(items: T[], seed: number): T[] {
  const out = items.slice();
  const rnd = mulberry32(seed);
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(rnd() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
